def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def _zip_product(name: str, files: list[str]) -> tuple[str, str]:
    os.makedirs(OUT, exist_ok=True)
    ver = vexx_version.__version__
    zname = f"vexx-{name}-{ver}.zip"
    zpath = os.path.join(OUT, zname)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as zf:
        for rel in files:
            src = os.path.join(ROOT, rel)
            if os.path.isfile(src):
                zf.write(src, rel)
    return zpath, _sha256(zpath)


def main():
    ver = vexx_version.__version__
    released = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    products = {}

    for key, flist in (
        ("cloner", CLONER_FILES),
        ("bot", BOT_FILES),
        ("ascii", ASCII_FILES),
    ):
        zpath, digest = _zip_product(key, flist)
        products[key] = {
            "version": ver,
            "zip": f"https://YOUR_CDN/updates/{os.path.basename(zpath)}",
            "sha256": digest,
        }
        print(f"{key}: {zpath}")

    exe = os.path.join(ROOT, "dist", "VexxCloner_release", "VexxCloner.exe")
    if os.path.isfile(exe):
        products["cloner"]["exe"] = {
            "url": "https://YOUR_CDN/updates/VexxCloner.exe",
            "sha256": _sha256(exe),
        }

    bundle_path, bundle_sha = _zip_product(
        "bundle",
        sorted(set(CLONER_FILES + BOT_FILES + ASCII_FILES)),
    )
    products["bundle"] = {
        "version": ver,
        "zip": f"https://YOUR_CDN/updates/{os.path.basename(bundle_path)}",
        "sha256": bundle_sha,
    }

    manifest = {
        "schema": 1,
        "channel": "stable",
        "released": released,
        "products": products,
    }
    mpath = os.path.join(OUT, "manifest.json")
    with open(mpath, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"\nmanifest: {mpath}")
    wjs = os.path.join(ROOT, "oauth_worker", "src", "updates_manifest.js")
    with open(wjs, "w", encoding="utf-8") as f:
        f.write("/** Auto-generated by pack_updates.py */\n")
        f.write("export const UPDATES_MANIFEST = ")
        f.write(json.dumps(manifest, indent=2, ensure_ascii=False))
        f.write(";\n")
    print(f"worker manifest: {wjs}")
    print("Upload dist/updates/* to CDN, fix zip URLs in manifest, then: cd oauth_worker && npx wrangler deploy")


if __name__ == "__main__":
    main()
