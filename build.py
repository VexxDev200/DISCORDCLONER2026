#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""One EXE: URL БД внутри, без databaseneon.txt снаружи."""

import base64
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
DIST = os.path.join(ROOT, "dist")
RELEASE = os.path.join(DIST, "VexxCloner_release")
_DB_FILE = os.path.join(ROOT, "databaseneon.txt")
_EMBED = os.path.join(ROOT, "db_embed.py")
_OBF_KEY = b"GC2026KV"


def read_db_url() -> str:
    if os.path.isfile(_DB_FILE):
        with open(_DB_FILE, "r", encoding="utf-8") as f:
            url = f.read().strip()
            if url:
                return url
    raise SystemExit(f"Missing database URL in {_DB_FILE}")


def write_schema_embed() -> None:
    schema_path = os.path.join(ROOT, "schema.sql")
    with open(schema_path, "r", encoding="utf-8") as f:
        sql = f.read()
    out = os.path.join(ROOT, "schema_embed.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by build.py\nSCHEMA_SQL = ")
        f.write(repr(sql))
        f.write("\n")


def write_db_embed(url: str) -> None:
    raw = url.encode("utf-8")
    enc = bytes(c ^ _OBF_KEY[i % len(_OBF_KEY)] for i, c in enumerate(raw))
    blob = base64.b64encode(enc).decode("ascii")
    with open(_EMBED, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by build.py\n")
        f.write(f"_BLOB = {blob!r}\n")
        f.write(f"_KEY = {_OBF_KEY!r}\n\n")
        f.write("def _decode():\n")
        f.write("    import base64\n")
        f.write("    e = base64.b64decode(_BLOB)\n")
        f.write("    return bytes(c ^ _KEY[i % len(_KEY)] for i, c in enumerate(e)).decode('utf-8')\n\n")
        f.write("DATABASE_URL = _decode()\n")


def pyinstaller_cmd() -> list:
    sep = os.pathsep
    return [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--onefile",
        "--console",
        "--noupx",
        "--name=VexxCloner",
        f"--add-data=schema.sql{sep}.",
        f"--runtime-hook={os.path.join(ROOT, 'pyi_rth_db.py')}",
        "--hidden-import=boot_db",
        "--hidden-import=db_embed",
        "--hidden-import=schema_embed",
        "--hidden-import=neon_store",
        "--hidden-import=app_paths",
        "--hidden-import=cloner_config",
        "--hidden-import=cloner_media",
        "--hidden-import=cloner_genome",
        "--hidden-import=cloner_dsl",
        "--hidden-import=cloner_ui",
        "--hidden-import=cloner_extras",
        "--hidden-import=psycopg",
        "--hidden-import=psycopg_binary",
        "--hidden-import=psycopg.pq",
        "--hidden-import=psycopg.types.json",
        "--collect-all=psycopg",
        "--collect-all=psycopg_binary",
        "--exclude-module=tkinter",
        "--exclude-module=matplotlib",
        "--exclude-module=PIL",
        "--exclude-module=pytest",
        "--exclude-module=IPython",
        "--exclude-module=numpy",
        os.path.join(ROOT, "discordcloner.py"),
    ]


def main():
    print("=== Vexx Cloner Builder (single EXE) ===\n")
    url = read_db_url()
    write_db_embed(url)
    write_schema_embed()
    print("DB URL + schema embedded into exe.\n")

    subprocess.check_call(pyinstaller_cmd(), cwd=ROOT)

    os.makedirs(RELEASE, exist_ok=True)
    src = os.path.join(DIST, "VexxCloner.exe")
    dst = os.path.join(RELEASE, "VexxCloner.exe")
    if not os.path.isfile(src):
        raise SystemExit(f"Build failed: {src} not found")
    shutil.copy2(src, dst)
    print(f"\nDone: {dst}")
    print("One file only. DB connection is inside the exe.")


if __name__ == "__main__":
    main()
